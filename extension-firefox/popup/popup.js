  state.isFromSearch = state.currentTab === 'search-results';

  const searchModal = $('search-modal');
  if (searchModal && !searchModal.classList.contains('hidden')) {
    searchModal.classList.add('hidden');
  }

  const imdbId = libraryItem._id || libraryItem.imdb_id || libraryItem.id;
  const type = libraryItem.type;

  renderDetailBasic(libraryItem);

  const isInLibrary = state.library.movies.some(m => m._id === imdbId) ||
    state.library.series.some(s => s._id === imdbId);

  const btnAdd = $('btn-add');
  const btnRemove = $('btn-remove');

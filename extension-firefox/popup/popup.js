async function handleTranslateDescription() {
  const descEl = $('detail-description');
  const btn = $('btn-translate');
  if (!descEl.textContent || btn.disabled) return;

  const t = I18N[state.language || 'ar'];

  // Toggle back to original if already translated
  if (descEl.dataset.original) {
    descEl.textContent = descEl.dataset.original;
    delete descEl.dataset.original;
    btn.innerHTML = `
      <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
        <path d="M4 12v8a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2v-8"/><polyline points="16 6 12 2 8 6"/><line x1="12" y1="2" x2="12" y2="15"/>
      </svg>
      <span data-i18n="translate_btn">${t.translate_btn || 'ترجمة'}</span>
    `;
    return;
  }

  const originalText = descEl.textContent;
  btn.disabled = true;
  btn.innerHTML = `<span style="display:inline-block;animation:spin 1s linear infinite;">↻</span> ${t.translate_loading || 'جاري...'}`;

  try {
    const targetLang = state.language === 'ar' ? 'ar' : 'en';
    const res = await fetch(`https://api.mymemory.translated.net/get?q=${encodeURIComponent(originalText)}&langpair=autodetect|${targetLang}`);
    const data = await res.json();
    if (data && data.responseData && data.responseData.translatedText) {
      descEl.dataset.original = originalText;
      descEl.textContent = data.responseData.translatedText;
      btn.innerHTML = `✓ ${t.translate_done || 'تمت'}`;
      setTimeout(() => {
        btn.disabled = false;
        btn.innerHTML = `
          <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
            <polyline points="1 4 1 10 7 10"/><path d="M3.51 15a9 9 0 1 0 2.13-9.36L1 10"/>
          </svg>
          <span data-i18n="translate_revert">${t.translate_revert || 'الأصلي'}</span>
        `;
      }, 3000);
    } else {
      throw new Error('Translation failed');
    }
  } catch (e) {
    console.error(e);
    btn.innerHTML = `✗ ${t.translate_error || 'خطأ'}`;
    setTimeout(() => {
      btn.disabled = false;
      btn.innerHTML = `
        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
          <path d="M4 12v8a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2v-8"/><polyline points="16 6 12 2 8 6"/><line x1="12" y1="2" x2="12" y2="15"/>
        </svg>
        <span data-i18n="translate_btn">${t.translate_btn || 'ترجمة'}</span>
      `;
    }, 3000);
  }
}


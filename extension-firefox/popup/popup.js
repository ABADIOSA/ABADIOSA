function switchTab(tabId) {
  state.currentTab = tabId;
  chrome.storage.local.set({ currentTab: tabId });
  $$('.tab-btn').forEach(b => b.classList.remove('active'));
  $$('.tab-content').forEach(c => c.classList.add('hidden'));
  const btn = document.querySelector(`[data-tab="${tabId}"]`);
  if (btn) {
    btn.classList.add('active');
    // Animate the tab indicator
    const indicator = document.querySelector('.tab-indicator');
    if (indicator) {
      indicator.style.width = `${btn.offsetWidth}px`;

      // Calculate position. Handle RTL correctly if offsetLeft behaves differently
      // In RTL, offsetLeft is still relative to offsetParent's left edge.
      indicator.style.transform = `translateX(${btn.offsetLeft}px)`;
    }
  }
  const contentId = tabId === 'search-results' ? 'tab-search-results-content' : `tab-${tabId}`;
  const content = $(contentId);
  if (content) content.classList.remove('hidden');
  updateLibrarySortUI();
}

